// Кэш для уже нормализованных слов
const normalizationCache = new Map<string, string>();

/**
 * Нормализует греческое слово, удаляя все диакритические знаки
 * @param greekWord - греческое слово с диакритикой
 * @returns нормализованное слово без диакритики
 */
export const normalizeGreekWord = (greekWord: string): string => {
  // Проверяем кэш
  const cached = normalizationCache.get(greekWord);
  if (cached) return cached;
  
  // Нормализуем каждый символ
  const normalized = Array.from(greekWord)
    .map(char => greekDiacriticsMap[char] || char)
    .join('');
  
  // Сохраняем в кэш
  normalizationCache.set(greekWord, normalized);
  
  return normalized;
};

/**
 * Нормализует массив греческих слов
 * @param greekWords - массив греческих слов
 * @returns массив нормализованных слов
 */
export const normalizeGreekWords = (greekWords: string[]): string[] => {
  return greekWords.map(normalizeGreekWord);
};

/**
 * Сравнивает два греческих слова без учета диакритики
 * @param word1 - первое слово
 * @param word2 - второе слово
 * @returns true если слова совпадают без учета диакритики
 */
export const areGreekWordsEqual = (word1: string, word2: string): boolean => {
  return normalizeGreekWord(word1) === normalizeGreekWord(word2);
};

/**
 * Проверяет, содержит ли текст греческие символы
 * @param text - текст для проверки
 * @returns true если текст содержит греческие буквы
 */
export const hasGreekLetters = (text: string): boolean => {
  const greekPattern = /[\u0370-\u03FF\u1F00-\u1FFF]/;
  return greekPattern.test(text);
};

/**
 * Очищает кэш нормализации (полезно при отладке)
 */
export const clearNormalizationCache = (): void => {
  normalizationCache.clear();
};

/**
 * Получает размер кэша (для отладки)
 */
export const getCacheSize = (): number => {
  return normalizationCache.size;
};

