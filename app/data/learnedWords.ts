// Номера Стронга из app/data/vocabulary.json, подгружаются при открытии главы
const vocabularyStrongs: Set<string> = new Set()

export const registerVocabularyStrongs = (strongs: string[]): void => {
  strongs.forEach((strong) => {
    if (strong) vocabularyStrongs.add(strong)
  })
}

// Функция проверки, должно ли слово быть изначально изученным
export const isInitiallyLearned = (strongNumber: string): boolean => {
  return initiallyLearnedWords.has(strongNumber) || vocabularyStrongs.has(strongNumber)
}

// Функция добавления нового слова в словарь
export const addInitiallyLearned = (strongNumber: string): void => {
  initiallyLearnedWords.add(strongNumber)
}

// Функция удаления слова из словаря
export const removeInitiallyLearned = (strongNumber: string): void => {
  initiallyLearnedWords.delete(strongNumber)
}

// Экспорт для отладки
export const getInitiallyLearnedCount = (): number => {
  return initiallyLearnedWords.size
}



